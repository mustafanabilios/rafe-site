  const setStatus = (root, kind, text) => {
    const status = root.querySelector("[data-waitlist-status]");
    if (!status) return;
    status.hidden = !text;
    status.dataset.kind = kind || "";
    status.textContent = text || "";
  };

  const bind = (root) => {
    const form = root.querySelector("form");
    if (!form || form.dataset.bound) return;
    form.dataset.bound = "1";
    const emailInput = form.querySelector('input[name="email"]');
    const honey = form.querySelector('input[name="company"]');
    const button = form.querySelector('button[type="submit"]');
    const thanks = root.querySelector("[data-waitlist-thanks]");

    form.addEventListener("submit", async (event) => {
      event.preventDefault();
      setStatus(root, "", "");
      const email = (emailInput?.value || "").trim();
      if (!email || !EMAIL_RE.test(email)) {
        setStatus(root, "error", "Please enter a valid email address.");
        emailInput?.focus();
        return;
      }
      if (honey && honey.value.trim()) {
        form.hidden = true;
        if (thanks) thanks.hidden = false;
        return;
      }
      const body = { [EMAIL_FIELD]: email };
      const country = countryFromTimezone();
      if (country) body[COUNTRY_FIELD] = country;
      if (button) button.disabled = true;
      try {
        const res = await fetch(ENDPOINT, {
          method: "POST",
          headers: { "Content-Type": "application/json", Accept: "application/json" },
          body: JSON.stringify(body),
        });
        if (!res.ok) throw new Error("submit");
        form.hidden = true;
        if (thanks) thanks.hidden = false;
        setStatus(root, "", "");
      } catch {
        setStatus(root, "error", "Something didn’t work. Please try again, or write to us from the footer.");
        if (button) button.disabled = false;
      }
    });
  };

  const start = () => document.querySelectorAll("[data-android-waitlist]").forEach(bind);
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
